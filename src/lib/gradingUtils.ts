/**
 * Shared assessment auto-grading utilities.
 *
 * Provides:
 *  - `gradeMathResponse`  — pure boolean: student answer vs expected answer
 *  - `processSubmission`   — full submission pipeline: grade all questions,
 *                            compute score/percentage/CBC level, return a
 *                            StudentSubmission-compatible object ready for storage.
 *
 * No React dependencies — safe to import from utilities, hooks, or services.
 */

import type { StudentSubmission } from "@/types/assessment";

// ─── Types ──────────────────────────────────────────────────────────────────

/** Result of grading a single question. */
export interface GradedAnswer {
  questionId: string;
  questionText: string;
  studentAnswer: string;
  correctAnswer: string;
  isCorrect: boolean;
  earnedPoints: number;
  possiblePoints: number;
  isGraded: boolean;
}

/** Minimal shape accepted by `processSubmission`. */
export interface GradingExam {
  id: string;
  title: string;
  questions: Array<{
    id: string;
    type: string;
    prompt?: string;
    text?: string;
    question?: string;
    points?: number;
    marks?: number;
    correctAnswer?: string;
    answer?: string;
    correctOptionId?: string;
    options?: Array<{ id: string; label: string; text: string }>;
    modelAnswer?: string;
  }>;
}

export interface GradingStudent {
  id: string;
  name?: string;
  fullName?: string;
  grade?: string;
  stream?: string;
  admissionNo?: string;
}

export interface StudentAnswers {
  [questionId: string]: string | undefined;
}

// ─── Pure grading helpers ────────────────────────────────────────────────────

/**
 * Evaluate a single math / numeric answer.
 *
 * Handles:
 *  - Exact string match after trim + lowercase ("12.5" === "12.5")
 *  - Fraction format "a/b"  ("1/2" → 0.5)
 *  - Decimal / integer extraction from strings with units ("10.953 kg" → 10.953)
 *  - Precision tolerance: 0.001 (so 0.333 matches 0.3333)
 */
export function gradeMathResponse(
  studentInput: unknown,
  expectedInput: unknown,
): boolean {
  if (
    studentInput === undefined ||
    studentInput === null ||
    studentInput === "" ||
    String(studentInput).trim() === ""
  )
    return false;

  const clean = (val: unknown) =>
    String(val ?? "").trim().toLowerCase().replace(/,/g, "");

  const studentStr = clean(studentInput);
  const expectedStr = clean(expectedInput);

  // 1. Exact match
  if (studentStr === expectedStr) return true;

  // 2. Parse numeric value (fraction or decimal)
  const parseNumericValue = (str: string): number => {
    // Fraction: "a/b"
    if (str.includes("/")) {
      const parts = str.split("/");
      if (parts.length === 2) {
        const num = parseFloat(parts[0].replace(/[^\d.-]/g, ""));
        const den = parseFloat(parts[1].replace(/[^\d.-]/g, ""));
        if (!isNaN(num) && !isNaN(den) && den !== 0) return num / den;
      }
    }
    // Decimal / integer: extract first match
    const match = str.match(/-?\d+(\.\d+)?/);
    return match ? parseFloat(match[0]) : NaN;
  };

  const numStudent = parseNumericValue(studentStr);
  const numExpected = parseNumericValue(expectedStr);

  if (!isNaN(numStudent) && !isNaN(numExpected)) {
    return Math.abs(numStudent - numExpected) < 0.001;
  }

  return false;
}

/**
 * Grade a single MCQ question.
 */
function gradeMCQ(
  studentAnswer: unknown,
  correctOptionId: string | undefined,
): boolean {
  return String(studentAnswer ?? "") === String(correctOptionId ?? "");
}

// ─── Full submission pipeline ────────────────────────────────────────────────

/**
 * Process a complete student submission — auto-grades every question and
 * returns a graded submission object compatible with `StudentSubmission`.
 *
 * No questions are left with `status: 'pending'` or `requiresManualGrading: true`.
 * All question types (mcq, structured, math, numeric, fill_blank, short_answer)
 * are evaluated immediately.
 *
 * @param exam          The exam definition with questions array.
 * @param student       The student metadata.
 * @param userAnswers   Map of questionId → student's answer string.
 * @param attemptId     Unique attempt identifier (generated by the caller).
 */
export function processSubmission(
  exam: GradingExam,
  student: GradingStudent,
  userAnswers: StudentAnswers,
  attemptId: string,
): Omit<StudentSubmission, "answers" | "marks"> & {
  answers: Record<string, unknown>;
  marks: Record<string, number>;
  gradedDetails: GradedAnswer[];
} {
  const questions = exam.questions ?? [];

  let totalEarnedMarks = 0;
  let totalPossibleMarks = 0;

  const answers: Record<string, unknown> = {};
  const marks: Record<string, number> = {};
  const gradedDetails: GradedAnswer[] = [];

  for (const question of questions) {
    const questionId = question.id ?? String(Math.random());
    const possiblePoints = Number(question.marks ?? question.points ?? 1);
    totalPossibleMarks += possiblePoints;

    // Resolve the student's answer — supports fallback keys
    const studentAns = String(
      userAnswers[questionId] ?? userAnswers[String(question.number ?? "")] ?? "",
    );

    // Resolve the correct answer
    const correctAns = String(
      question.correctAnswer ?? question.answer ?? question.correctOptionId ?? "",
    );

    // Determine correct
    let isCorrect = false;
    if (question.type === "mcq") {
      isCorrect = gradeMCQ(studentAns, question.correctOptionId);
    } else {
      // structured / math / numeric / fill_blank / short_answer — use math evaluator
      isCorrect = gradeMathResponse(studentAns, correctAns);
    }

    const earnedPoints = isCorrect ? possiblePoints : 0;
    totalEarnedMarks += earnedPoints;

    answers[questionId] = studentAns;
    marks[questionId] = earnedPoints;
    gradedDetails.push({
      questionId,
      questionText: question.prompt ?? question.text ?? question.question ?? "",
      studentAnswer: studentAns,
      correctAnswer: correctAns,
      isCorrect,
      earnedPoints,
      possiblePoints,
      isGraded: true, // every question is explicitly graded
    });
  }

  const percentage =
    totalPossibleMarks > 0
      ? Math.round((totalEarnedMarks / totalPossibleMarks) * 100)
      : 0;

  // CBC performance level
  let performanceLevel = "BE";
  if (percentage >= 80) performanceLevel = "EE";
  else if (percentage >= 65) performanceLevel = "ME";
  else if (percentage >= 50) performanceLevel = "AE";

  return {
    id: `sub_${Date.now()}_${student.id}_${attemptId}`,
    studentId: student.id,
    studentName: student.name ?? student.fullName ?? student.id,
    examId: exam.id,
    examTitle: exam.title,
    score: totalEarnedMarks,
    totalPoints: totalPossibleMarks,
    percentage,
    level: performanceLevel,
    status: "completed",
    hasPendingStructured: false,
    requiresManualGrading: false,
    admissionNo: student.admissionNo ?? "",
    grade: student.grade,
    stream: student.stream ?? "All",
    answers,
    marks,
    gradedDetails,
    submittedAt: new Date().toISOString(),
  };
}
